/**
 * Real product captures used on marketing pages, generated from `./assets`.
 * Every file is a screenshot or screen recording of the running app; see the
 * PR's `.github/assets/<branch>/README.md` for when and how each was captured.
 * Files are imported with `?url`, so Vite emits them content-hashed under
 * `/assets/` (long-lived caching) and only marketing chunks reference them.
 */

export interface ImageVariant {
  /** Intrinsic size of the largest file, used for width/height (no layout shift). */
  width: number;
  height: number;
  /** `srcset` strings, smallest first. */
  avif: string;
  webp: string;
  /** Largest WebP, for `src`. */
  fallback: string;
}

export interface MediaEntry {
  /** Desktop or landscape capture (the poster when `video` is set). */
  wide: ImageVariant;
  /** Optional phone capture: preferred below the `sm` breakpoint, and the overlay in the hero composition. */
  phone?: ImageVariant;
  /** Optional dark-theme captures. */
  wideDark?: ImageVariant;
  phoneDark?: ImageVariant;
  /** Optional screen recording, mounted only when the visitor presses play. */
  video?: { src: string; width: number; height: number };
}

const variant = (width: number, height: number, files: [number, string, string][]): ImageVariant => ({
  width,
  height,
  avif: files.map(([w, avif]) => `${avif} ${w}w`).join(', '),
  webp: files.map(([w, , webp]) => `${webp} ${w}w`).join(', '),
  fallback: files[files.length - 1]?.[2] ?? '',
});

