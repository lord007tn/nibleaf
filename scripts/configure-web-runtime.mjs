import { createHash, randomUUID } from 'node:crypto';
import { existsSync } from 'node:fs';
import { readdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';

// The shared Docker image uses reserved origins; ordinary Vite builds keep
// their existing configuration. Origins must remain safe in generated JS.
function origin(value, name) {
  const url = new URL(value);
  if (
    !['http:', 'https:'].includes(url.protocol) ||
    !/^[a-z0-9.:[\]-]+$/i.test(url.host) ||
    url.username ||
    url.password ||
    url.pathname !== '/' ||
    url.search ||
    url.hash
  ) {
    throw new Error(`${name} must be an HTTP(S) origin without credentials, a path, query, or fragment.`);
  }
  return url.origin;
}

const output = process.argv[2];
if (!output) throw new Error('Usage: node scripts/configure-web-runtime.mjs <output-directory>');
const siteDomain = (process.env.SITE_BASE_DOMAIN ?? '').trim().replace(/^\*\./, '').replace(/\.$/, '');
if (siteDomain && !/^[a-z0-9.-]+(?::[0-9]+)?$/i.test(siteDomain)) throw new Error('SITE_BASE_DOMAIN must be a hostname.');
const replacements = [
  ['https://nibleaf-runtime-app.invalid', origin(process.env.APP_URL, 'APP_URL')],
  ['https://nibleaf-runtime-admin.invalid', origin(process.env.ADMIN_URL?.trim() || 'http://localhost:4315', 'ADMIN_URL')],
  ['http://nibleaf-runtime-api.invalid', origin(process.env.API_URL?.trim() || 'http://server:4311', 'API_URL')],
  ['nibleaf-runtime-site.invalid', siteDomain],
];
const changedAssets = new Map();
const configuredFile = join(output, '.nibleaf-runtime-configured');

async function atomicWrite(path, content, mode = 0o644) {
  const temporary = `${path}.${process.pid}-${randomUUID()}.tmp`;
  try {
    await writeFile(temporary, content, { mode, flag: 'wx' });
    await rename(temporary, path);
  } finally {
    await rm(temporary, { force: true });
  }
}

async function configure(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      await configure(path);
    } else if (entry.isFile() && /\.(?:m?js|json|html)$/.test(entry.name)) {
      const template = `${path}.nibleaf-runtime-template`;
      const source = await readFile(existsSync(template) ? template : path, 'utf8');
      if (!replacements.some(([marker]) => source.includes(marker))) {
        if (existsSync(template)) await atomicWrite(path, source);
        continue;
      }
      // Persist the original atomically before changing any generated bytes.
      if (!existsSync(template)) await atomicWrite(template, source, 0o600);
      let configured = source;
      for (const [marker, value] of replacements) configured = configured.replaceAll(marker, value);
      if (/nibleaf-runtime-(?:app|admin|api|site)\.invalid/.test(configured))
        throw new Error('Runtime configuration still contains reserved build markers.');
      await atomicWrite(path, configured);
      if (path.startsWith(join(output, 'public'))) {
        changedAssets.set(resolve(path), {
          size: Buffer.byteLength(configured),
          etag: `"${createHash('sha256').update(configured).digest('hex')}"`,
          mtime: new Date().toISOString(),
        });
      }
      // Remove encodings of the original bytes from disk and from the manifest.
      await Promise.all(['.gz', '.br', '.zst'].map((suffix) => rm(`${path}${suffix}`, { force: true })));
    }
  }
}

async function configureManifest() {
  if (!changedAssets.size) return;
  const entry = join(output, 'server', 'index.mjs');
  const source = await readFile(entry, 'utf8');
  const template = `${entry}.nibleaf-runtime-template`;
  if (!existsSync(template)) await atomicWrite(template, source, 0o600);
  // Nitro emits a tab-indented JSON object, ending at the top-level brace.
  const manifestPattern = /(var public_assets_data_default = )(\{[\s\S]*?\n\});/;
  const matcher = 'createMatcherFromFind(findRouteRules)';
  if (!manifestPattern.test(source) || !source.includes(matcher)) {
    throw new Error('Unsupported Nitro public asset manifest or route matcher; runtime configuration cannot be served safely.');
  }
  const rewrittenPaths = [];
  const configured = source.replace(manifestPattern, (_, declaration, json) => {
    const assets = JSON.parse(json);
    for (const [id, asset] of Object.entries(assets)) {
      const path = resolve(dirname(entry), asset.path);
      const metadata = changedAssets.get(path);
      if (metadata) {
        Object.assign(asset, metadata);
        rewrittenPaths.push(id);
      } else if (changedAssets.has(path.replace(/\.(?:gz|br|zst)$/, ''))) delete assets[id];
    }
    return `${declaration}${JSON.stringify(assets)};`;
  });
  // Keep Nitro's global immutable rule. Only exact rewritten paths override
  // cache-control, retaining all inherited security headers and other rules.
  const runtimeMatcher = `createMatcherFromFind((method, pathname) => {
    const layers = findRouteRules(method, pathname);
    if (!${JSON.stringify(rewrittenPaths)}.includes(pathname)) return layers;
    return layers.map(layer => ({ ...layer, data: { ...layer.data,
      rules: layer.data.rules.map(rule => rule.name === "headers"
        ? { ...rule, options: { ...rule.options, "cache-control": "public, max-age=0, must-revalidate" } }
        : rule)
    } }));
  })`;
  await atomicWrite(entry, configured.replace(matcher, runtimeMatcher));
}

try {
  // The wrapper must refuse a previous receipt if configuration is interrupted.
  await rm(configuredFile, { force: true });
  await configure(output);
  await configureManifest();
  await atomicWrite(configuredFile, 'Runtime configuration complete\n', 0o600);
} catch (error) {
  if (['EROFS', 'EACCES', 'EPERM'].includes(error.code)) {
    throw new Error(
      `Web runtime output '${output}' is not writable (${error.code}). Allow the service UID to write this output directory, or mount a writable copy before running the configurator. No web service was started.`,
      { cause: error },
    );
  }
  throw error;
}
